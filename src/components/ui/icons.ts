export type MaterialName = keyof typeof MATERIAL_TO_FA
export type IconName = (typeof MATERIAL_TO_FA)[MaterialName]

/** Canvas (Material) icon name -> FA name. Unknown names throw in development. */
export function iconFor(material: string): IconName {
  const fa = (MATERIAL_TO_FA as Record<string, IconName>)[material]
  if (fa !== undefined) return fa
  if (import.meta.env.DEV) throw new Error(`[icons] Unknown icon "${material}"`)
  return 'circle-exclamation'
}

export function iconDefinition(name: string): IconDefinition | undefined {
  return REGISTRY[name]
}
